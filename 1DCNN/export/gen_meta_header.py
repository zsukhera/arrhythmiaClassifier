"""
Write <tag>/<tag>_model_meta.h: tensor order, int8 quantisation parameters,
decision thresholds (float and int8-domain) and preprocessing constants that
the firmware must match.  Values are read from the .tflite itself.

Usage: .venv-export/bin/python 1DCNN/export/gen_meta_header.py P1 int8_ptq
"""
import json
import math
import sys
from pathlib import Path

import numpy as np
import tensorflow as tf

HERE = Path(__file__).resolve().parent
tag, variant = sys.argv[1], sys.argv[2]
R = json.loads((HERE / tag / "report.json").read_text())
b = (HERE / tag / f"{tag}_{variant}.tflite").read_bytes()
it = tf.lite.Interpreter(model_content=b)
ins, outs = it.get_input_details(), it.get_output_details()
K = int(outs[0]["shape"][-1])
P = tag.upper()
L = [f"// Auto-generated by 1DCNN/export/gen_meta_header.py for {tag}_{variant}.tflite",
     f"// Pair with {tag.lower()}_{variant}.h (model bytes).",
     f"#ifndef {P}_MODEL_META_H", f"#define {P}_MODEL_META_H", "",
     "// ---- preprocessing that the model was trained with (must match exactly) ----",
     "#define FARAG_FS_HZ            128   // resample to 128 Hz (resample_poly 16/45 from 360 Hz)",
     "#define FARAG_WIN_BEFORE_R     32    // 64-sample window: R-32 .. R+31",
     "#define FARAG_WIN_AFTER_R      32",
     "#define FARAG_NK               32    // model input = central 32 samples of the 64-sample derivative",
     "#define FARAG_RR_LOCAL_BEATS   80    // causal mean of last 80 pre-RR (incl. current)",
     "#define FARAG_RR_GLOBAL_BEATS  400   // causal mean of last 400 pre-RR (incl. current)",
     "// ECG input: x = window in mV; x -= mean(x); d[i] = x[i+1]-x[i] (d[63]=d[62]);",
     "//            ecg_in[k] = d[16+k], k = 0..31",
     "// RR input : {pre/local, pre/global, post/local, post/global}  (needs the NEXT R peak)", ""]
for d in ins:
    nm = "ECG" if len(d["shape"]) == 3 else "RR"
    s, z = d["quantization"]
    L += [f"#define {P}_IN_{nm}_INDEX   {ins.index(d)}   // interpreter->input({ins.index(d)}), shape {list(d['shape'])}, {np.dtype(d['dtype']).name}"]
    if d["dtype"] == np.int8:
        L += [f"#define {P}_IN_{nm}_SCALE   {s:.9g}f",
              f"#define {P}_IN_{nm}_ZP      {int(z)}   // q = clamp(round(x / scale) + zp, -128, 127)"]
s, z = outs[0]["quantization"]
L += ["", f"#define {P}_N_CLASSES {K}"]
if outs[0]["dtype"] == np.int8:
    L += [f"#define {P}_OUT_SCALE {s:.9g}f", f"#define {P}_OUT_ZP    {int(z)}   // p = (q - zp) * scale"]
if K == 3:
    t = R["tau_s"]
    L += ["// classes: 0 = N, 1 = S (SVEB), 2 = V (VEB)",
          f"// decision: if P(S) >= TAU_S predict S, else argmax (calibrated on DS1, official P1 run)",
          f"#define {P}_TAU_S {t:.2f}f"]
    if outs[0]["dtype"] == np.int8:
        L += [f"#define {P}_TAU_S_Q {math.ceil(t / s + z - 1e-9)}   // int8 domain: q_S >= this"]
else:
    t = R["bin_t"]
    L += ["// classes: 0 = Normal (AAMI N), 1 = Arrhythmia (AAMI S/V/F/Q)",
          f"// decision: arrhythmia if P(1) >= T_ARR (chosen on the DS1 hold-out); 0.5 = plain argmax",
          f"#define {P}_T_ARR {t:.2f}f"]
    if outs[0]["dtype"] == np.int8:
        L += [f"#define {P}_T_ARR_Q {math.ceil(t / s + z - 1e-9)}   // int8 domain: q_arr >= this"]
L += ["", f"#define {P}_TFLITE_BYTES {len(b)}"]
tf_rep = HERE / tag / "tflm_report.json"
if tf_rep.exists():
    a = json.loads(tf_rep.read_text()).get(variant, {}).get("tflm_arena_bytes_host64")
    if a:
        L += [f"// TFLM arena measured on host (64-bit pointers): {a} B; ESP32-S3 needs <= this.",
              f"#define {P}_TENSOR_ARENA_BYTES {int(math.ceil((a + 1024) / 16) * 16)}  // + 1 KB head-room"]
L += ["// Ops to register (MicroMutableOpResolver): " + ", ".join(
    o for o in R["variants"][variant]["memory"]["op_types"] if o != "DELEGATE"), "",
      f"#endif  // {P}_MODEL_META_H", ""]
(HERE / tag / f"{tag.lower()}_model_meta.h").write_text("\n".join(L))
print("\n".join(L))
